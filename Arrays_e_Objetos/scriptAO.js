// ARRAY DE OBJETOS NO JAVASCRIPT


//OBJETOS - Criando um objeto chamado usuario
let usuario = {


//Propriedades do objeto - valor
    nome: "João",
    idade: 30,
    cidade: "Joinville"
}
console.log(usuario);


//Acessando as propriedades do objeto
console.log(usuario.nome);
console.log(usuario.idade);
console.log(usuario.cidade);

//Adicionando uma nova propriedade ao objeto
usuario.email = "joao@email.com";
console.log(usuario);

